-- claude.nvim — a Neovim colorscheme that matches the terminal and `ls`.
--
-- Every hue is the iTerm2 "Default" profile's (the SF Mono Nerd dynamic
-- profile inherits it): its background, foreground, cursor and selection,
-- and its ANSI 16, which is all eza paints `ls` with. iTerm's "Use Bright
-- Bold" renders eza's bold names in the bright slots, so directories are
-- bright blue and executables bright green here too. The ANSI 16 are the
-- same in iTerm's light and dark modes, so both tables share them and differ
-- only in the neutrals, which are offsets from each mode's background
-- (docs/adr/0003). lua/appearance.lua flips vim.o.background from the
-- terminal's OSC 11 reply, which selects the light or dark palette below.

